from src.公共.数据结构 import 操作步骤数据
from src.公共.枚举定义 import 操作类型枚举
from src.公共.异常定义 import 参数非法异常
from src.公共.日志管理 import 获取日志管理器


class 步骤管理服务类:
    """操作步骤管理服务"""

    def __init__(self, 步骤DAO=None):
        self.步骤DAO = 步骤DAO
        self.日志 = 获取日志管理器("步骤管理服务")

    def 查询脚本步骤(self, 脚本标识: int) -> list[操作步骤数据]:
        """查询指定脚本的顶层操作步骤，按排序序号排列"""
        return self.步骤DAO.查询By脚本(脚本标识)

    def 查询脚本全部步骤(self, 脚本标识: int) -> list[操作步骤数据]:
        """查询指定脚本的所有步骤（含子步骤）"""
        return self.步骤DAO.查询By脚本全部(脚本标识)

    def 查询步骤树(self, 脚本标识: int) -> tuple[list[操作步骤数据], dict[int, dict[str, list[操作步骤数据]]]]:
        """查询完整步骤树，返回(顶层步骤列表, {父步骤标识: {分支类型: [子步骤列表]}})"""
        全部步骤 = self.步骤DAO.查询By脚本全部(脚本标识)
        顶层步骤 = [s for s in 全部步骤 if s.父步骤标识 is None]
        步骤树: dict[int, dict[str, list[操作步骤数据]]] = {}
        for 步骤 in 全部步骤:
            if 步骤.父步骤标识 is not None:
                if 步骤.父步骤标识 not in 步骤树:
                    步骤树[步骤.父步骤标识] = {}
                分支 = 步骤.分支类型 or "是"
                if 分支 not in 步骤树[步骤.父步骤标识]:
                    步骤树[步骤.父步骤标识][分支] = []
                步骤树[步骤.父步骤标识][分支].append(步骤)
        return 顶层步骤, 步骤树

    def 添加步骤(self, 脚本标识: int, 步骤数据: 操作步骤数据, 插入位置: int | None = None,
                  父步骤标识: int | None = None, 分支类型: str | None = None) -> int:
        """向脚本添加操作步骤，支持指定插入位置、父步骤和分支类型"""
        步骤数据.所属脚本标识 = 脚本标识
        步骤数据.父步骤标识 = 父步骤标识
        步骤数据.分支类型 = 分支类型
        if 插入位置 is not None:
            if 父步骤标识 is not None:
                现有步骤 = self.步骤DAO.查询子步骤(父步骤标识, 分支类型)
            else:
                现有步骤 = self.步骤DAO.查询By脚本(脚本标识)
            for 步骤 in 现有步骤:
                if 步骤.排序序号 >= 插入位置:
                    步骤.排序序号 += 1
            排序映射 = {s.步骤标识: s.排序序号 for s in 现有步骤 if s.排序序号 >= 插入位置}
            if 排序映射:
                self.步骤DAO.批量更新排序(排序映射)
            步骤数据.排序序号 = 插入位置
        else:
            if 父步骤标识 is not None:
                现有步骤 = self.步骤DAO.查询子步骤(父步骤标识, 分支类型)
            else:
                现有步骤 = self.步骤DAO.查询By脚本(脚本标识)
            步骤数据.排序序号 = len(现有步骤) + 1
        return self.步骤DAO.插入(步骤数据)

    def 修改步骤(self, 步骤标识: int, 步骤数据: 操作步骤数据) -> None:
        """修改操作步骤参数，保护排序序号不被重置"""
        if not 步骤数据.排序序号 or 步骤数据.排序序号 < 1:
            原步骤 = self.步骤DAO.查询ById(步骤标识)
            if 原步骤:
                步骤数据.排序序号 = 原步骤.排序序号
        self.步骤DAO.更新(步骤标识, 步骤数据)

    def 删除步骤(self, 步骤标识: int) -> None:
        """删除操作步骤（CASCADE自动删除子步骤）"""
        self.步骤DAO.删除(步骤标识)

    def 拖动排序(self, 脚本标识: int, 原序号: int, 新序号: int) -> None:
        """拖动调整步骤顺序，事务更新所有受影响步骤的排序序号"""
        if 原序号 == 新序号:
            return
        现有步骤 = self.步骤DAO.查询By脚本(脚本标识)
        排序映射 = {}
        if 原序号 < 新序号:
            for 步骤 in 现有步骤:
                if 步骤.排序序号 == 原序号:
                    排序映射[步骤.步骤标识] = 新序号
                elif 原序号 < 步骤.排序序号 <= 新序号:
                    排序映射[步骤.步骤标识] = 步骤.排序序号 - 1
        else:
            for 步骤 in 现有步骤:
                if 步骤.排序序号 == 原序号:
                    排序映射[步骤.步骤标识] = 新序号
                elif 新序号 <= 步骤.排序序号 < 原序号:
                    排序映射[步骤.步骤标识] = 步骤.排序序号 + 1
        if 排序映射:
            self.步骤DAO.批量更新排序(排序映射)

    def 规范化排序序号(self, 脚本标识: int) -> None:
        """将脚本步骤的排序序号重新编为连续的 1,2,3...，消除删除产生的缺口"""
        现有步骤 = self.步骤DAO.查询By脚本(脚本标识)
        排序映射 = {}
        for 索引, 步骤 in enumerate(现有步骤, 1):
            if 步骤.排序序号 != 索引:
                排序映射[步骤.步骤标识] = 索引
        if 排序映射:
            self.步骤DAO.批量更新排序(排序映射)

    def 批量修改延时(self, 脚本标识: int, 步骤标识列表: list[int], 延时毫秒: int) -> None:
        """批量修改步骤间延时"""
        现有步骤 = self.步骤DAO.查询By脚本全部(脚本标识)
        for 步骤 in 现有步骤:
            if 步骤.步骤标识 in 步骤标识列表:
                步骤.步骤延时 = 延时毫秒
                self.步骤DAO.更新(步骤.步骤标识, 步骤)

    def 复制步骤(self, 步骤标识: int, 目标位置: int) -> int:
        """复制步骤并粘贴到指定位置"""
        原步骤 = self.步骤DAO.查询ById(步骤标识)
        if 原步骤 is None:
            return 0
        脚本标识 = 原步骤.所属脚本标识
        新步骤 = 操作步骤数据(
            所属脚本标识=脚本标识,
            操作类型=原步骤.操作类型,
            排序序号=目标位置,
            目标坐标X=原步骤.目标坐标X,
            目标坐标Y=原步骤.目标坐标Y,
            按键值=原步骤.按键值,
            修饰键列表=原步骤.修饰键列表,
            输入文本=原步骤.输入文本,
            步骤延时=原步骤.步骤延时,
            滚轮量=原步骤.滚轮量,
            按键保持时长=原步骤.按键保持时长,
            延时时长=原步骤.延时时长,
            起点坐标X=原步骤.起点坐标X,
            起点坐标Y=原步骤.起点坐标Y,
            终点坐标X=原步骤.终点坐标X,
            终点坐标Y=原步骤.终点坐标Y,
            OCR区域左上角X=原步骤.OCR区域左上角X,
            OCR区域左上角Y=原步骤.OCR区域左上角Y,
            OCR区域右下角X=原步骤.OCR区域右下角X,
            OCR区域右下角Y=原步骤.OCR区域右下角Y,
            OCR识别语言=原步骤.OCR识别语言,
            OCR条件类型=原步骤.OCR条件类型,
            OCR目标文本=原步骤.OCR目标文本,
            OCR逻辑关系=原步骤.OCR逻辑关系,
            OCR超时时间=原步骤.OCR超时时间,
            OCR轮询间隔=原步骤.OCR轮询间隔,
            OCR超时处理=原步骤.OCR超时处理,
            父步骤标识=原步骤.父步骤标识,
            分支类型=原步骤.分支类型,
        )
        return self.添加步骤(脚本标识, 新步骤, 目标位置,
                              父步骤标识=原步骤.父步骤标识, 分支类型=原步骤.分支类型)

    def 变更操作类型(self, 步骤标识: int, 新类型: str) -> None:
        """变更操作类型，清除原类型特有参数"""
        合法类型 = {e.value for e in 操作类型枚举}
        if 新类型 not in 合法类型:
            raise 参数非法异常(f"不合法的操作类型: {新类型}")
        步骤 = self.步骤DAO.查询ById(步骤标识)
        if 步骤 is None:
            return
        步骤.操作类型 = 新类型
        步骤.目标坐标X = None
        步骤.目标坐标Y = None
        步骤.按键值 = None
        步骤.修饰键列表 = None
        步骤.输入文本 = None
        步骤.滚轮量 = None
        步骤.按键保持时长 = None
        步骤.延时时长 = None
        步骤.起点坐标X = None
        步骤.起点坐标Y = None
        步骤.终点坐标X = None
        步骤.终点坐标Y = None
        步骤.OCR区域左上角X = None
        步骤.OCR区域左上角Y = None
        步骤.OCR区域右下角X = None
        步骤.OCR区域右下角Y = None
        步骤.OCR识别语言 = None
        步骤.OCR条件类型 = None
        步骤.OCR目标文本 = None
        步骤.OCR逻辑关系 = None
        步骤.OCR超时时间 = None
        步骤.OCR轮询间隔 = None
        步骤.OCR超时处理 = None
        self.步骤DAO.更新(步骤标识, 步骤)
